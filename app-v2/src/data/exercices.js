/** Materiel exact : 'elastique' | 'kettlebell' | 'halteres' | 'barre' | 'machine' | 'rien' | 'traction'. */
export function materielPrecis(ex) {
  if (!ex) return null;
  if (ELASTIQUE_IDS.has(ex.imgId)) return 'elastique';
  if (KETTLEBELL_IDS.has(ex.imgId)) return 'kettlebell';
  return ex.mat;
}

